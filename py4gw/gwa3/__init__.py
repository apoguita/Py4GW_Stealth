"""The GwAu3-compatible layer: GwAu3's names, Stealth's engine.

**A Stealth-owned component, not a port of Reforged.** Its specification is GwAu3's own public
surface and it is recorded in ``docs/GWA3_COMPAT_SPEC.md``. It sits outside the ported surface
deliberately: this package imports the ported classes and is imported by none of them, so no
``GwAu3_*`` name and no ``GC_*`` constant appears anywhere else under ``py4gw/``.

The contract, in one line: **GwAu3 supplies the names, the arguments, the defaults and the return
shapes; Stealth supplies the implementation, the layout and the safety rules.** Where the two cannot
meet, the caller is told which one gave way and why, by name -- never given a plausible wrong value.

What exists today
-----------------

``constants``
    GwAu3's whole constant surface, generated from every ``.au3`` file under ``external/GwAu3/API/``
    by ``tools/generate_gwa3_constants.py`` -- ``Global Const`` and ``Global Enum`` both, because 129
    of the names are declared the second way. 7,480 names, with GwAu3's leading ``$`` dropped, so
    ``$GC_I_ALLEGIANCE_ENEMY`` reads ``GC_I_ALLEGIANCE_ENEMY``.

    .. code-block:: python

        from py4gw.gwa3 import constants

        constants.GC_I_ALLEGIANCE_ENEMY   # 3

``data_agent``
    GwAu3's ``Agent_*`` readers over the records this project already reads, generated by
    ``tools/generate_gwa3_data_agent.py``: ``Agent_GetAgentInfo`` with **all 143** of GwAu3's field
    keys, and its seven siblings (``Agent_GetMyID``, ``GetMyID``, ``Agent_GetCurrentTarget``,
    ``Agent_ConvertID``, ``Agent_GetAgentPtr``, ``Agent_GetMaxAgents``, and the three distance
    helpers).

    .. code-block:: python

        from py4gw.gwa3 import data_agent

        data_agent.Agent_GetAgentInfo(-2, "X")       # the controlled character's X
        data_agent.Agent_GetAgentInfo(-1, "Allegiance")

    Three of the 143 keys -- ``EffectCount``, ``BondCount`` and ``VisibleEffectCount`` -- walk a
    linked list that lives in the client's memory and therefore need the connection; from a
    materialized record they **raise**, naming what they need rather than answering a wrong value.
    ``HasVisibleEffects`` does the same.

``data_skill``
    GwAu3's skill-table reader, ``Skill_GetSkillInfo`` -- all **63** of its keys, over the client's own
    constant skill table, which this project reads as ``SkillStruct``.

    .. code-block:: python

        from py4gw.gwa3 import data_skill

        data_skill.Skill_GetSkillInfo(1062, "EnergyCost")
        data_skill.Skill_GetSkillInfo(1062, "Recharge")

``data_party``
    GwAu3's party-**context** reader, ``Party_GetPartyContextInfo`` -- all **14** of its keys. Six are
    refused with a reason: GwAu3 reads them through the context's ``player_party_ptr``, which points at
    a second record this layer does not follow yet.

``data_item``
    GwAu3's item reader, ``Item_GetItemInfoByItemID`` -- **39** keys over the client's item records,
    which this project reads as ``ItemStruct`` (its offsets match GwAu3's exactly). Five refuse with a
    reason: three dye bytes live inside a structure the port does not name, and the three decoded-name
    keys need a decode handshake (`PyItem.RequestName` then `GetName`) whose sequencing is outstanding.

``data_quest``
    GwAu3's quest-log reader, ``Quest_GetQuestInfo`` -- **22** keys. GwAu3 walks the log with a
    ``0x34`` stride from ``+0x52C``; this project walks the same array and reads `QuestStruct`, whose
    size is exactly that stride. Ten keys refuse: the eight text keys decode on the game thread, and
    two return raw client addresses.

``core``
    GwAu3's ``Core_*``: **every GwAu3 script's first two lines live here**. ``Core_Initialize`` is the
    connection -- GwAu3 opens the process, scans its own byte signatures and fills a global pointer
    table, and this project's ``py4gw.connect()`` is that same job already done -- and it keeps GwAu3's
    contract of ``1`` on success, ``0`` on failure. The three status words a script gates on
    (``Core_IsIngame``, ``Core_IsLoginScreen``, ``Core_IsCharacterSelection`` and their readers) are
    **refused**: GwAu3 resolves them by its own byte patterns into client globals this project has no
    resolver for, and answering them from ``Map.IsMapReady()`` would be a different question under the
    same name. ``Core_AutoStart`` and ``Core_GetGuildWarsWindow`` are AutoIt-side and are transcribed
    in ``tools/autoit/Stealth_GwAu3.au3``, because they call back into the script itself.
    ``Memory_Read`` and ``Memory_ReadPtr`` -- ``GwAu3_Core_Memory.au3``'s two plain reads -- are here
    too: they accept what this layer produces (a record it read, or the address ``Memory_ReadPtr``
    answered) and read it through this project's own ``ProcessMemoryReader``, which is the port of
    ``ReadProcessMemory``.

``core_utils``
    GwAu3's list walkers -- ``Utils_TList_CreateIterator``, ``Utils_TList_Iterator_Current``,
    ``Utils_TList_Iterator_Next`` and ``Utils_TLink_IsLinked`` -- over **this project's own lists**: the
    argument is the list a ported walk hands out (``AgentLivingStruct.visible_effects``,
    ``PartyContextStruct.request``/``.sending``) and the iterator answers the port's records where
    GwAu3's answers node addresses.

``pathfinder_core``
    ``Pathfinder_Initialize`` and ``Pathfinder_IsMapAvailable``: the state pair a pathing caller gates
    on, answered from this project's own pathing table (``Map.Pathing.GetAvailableMapIds``) rather than
    from GwAu3's downloaded ``maps.rar`` and its ``GWPathfinder.dll``.

``log``
    GwAu3's ``Log_*``: levels, the debug gate, the registered callback and the RichEdit renderer. Also
    AutoIt-side -- a log line renders into the script's own control -- so the whole module is
    transcribed in the UDF rather than bridged.

``uai_agent``, ``uai_utils``, ``uai_effects``, ``uai_filter``, ``uai_get_agent``, ``uai_const``
    GwAu3's ``UAI_*`` combat plugin, in progress and split the way the plugin is: the arithmetic and
    profession helpers, the agent-cache column accessors over this project's live reads, the effect and
    bond questions, all sixty-four ``UAI_Filter_*`` predicates, all twenty-six of
    ``UtilityAI_GetAgent.au3``'s targeting and positioning functions, and the plugin's mutable settings.

``uai_core``, ``uai_cache``, ``uai_can_cast``, ``uai_static_skill_cache``,
``uai_dynamic_skill_cache``, ``uai_best_target_cache``, ``uai_can_use_cache``, ``uai_weaponsets``
    The engine a script calls and the decisions it makes: ``UAI_Fight`` and the slot loop
    (``UAI_UseSkills``, ``UAI_TryUseSkill``, ``UAI_UseSkillEx``), the two per-frame caches as the
    names they hold live, the cast-sensibility chain, and the four weapon sets -- their weapons, their
    mods and the scores that choose between them. ``uai_strategy_*`` and ``uai_anti`` are the
    per-skill ranking bodies the dispatch reaches.

What does not exist yet
----------------------

**Three routes inside the ``UAI_*`` plugin, and the AutoIt-side pipe.** Every ``Cmd_*`` module ships --
all eighteen of them -- the read families are all in place, and the ``UAI_*`` surface above is built
except for what each refusing member names: the sixteen plugin members that call something this layer
does not have (eleven ``Anti_*`` guards, the two NPC-flag predicates, the avoid-list predicate and the
cache row index), the mid-cast cancel and the weapon-set switch (both ``Core_PerformAction``, the
injected action queue this project does not write into), and the per-skill bodies whose GwAu3 source
calls a name this layer does not implement. On the transport side the named pipe is specified but not
built; stdio carries the protocol.

Until they land, the ported classes are what to call -- ``py4gw.Agent``, ``py4gw.Map``,
``py4gw.Party``, ``py4gw.Item``, ``py4gw.Player`` and the rest -- and the route each GwAu3 routine
will take is recorded in ``docs/GWA3_ROUTE_MAP.md``, which tiers the union of GwAu3's module
declarations and every function its own scripts call.
"""

